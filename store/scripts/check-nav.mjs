// Checks navigation behaviour in a real browser, and captures open-menu screenshots.
import { mkdirSync } from "node:fs";
import { launchBrowser } from "./lib/staging-auth.mjs";
const base = process.env.BASE_URL ?? "http://localhost:3100";
const out = new URL("../screenshots/phase-b/", import.meta.url);
mkdirSync(out, { recursive: true });
const browser = await launchBrowser();
let failed = 0;
const check = (name, pass, detail = "") => { console.log(`${pass ? "PASS" : "FAIL"}  ${name}${detail ? `  (${detail})` : ""}`); if (!pass) failed++; };

const d = await (await browser.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
await d.goto(`${base}/design`, { waitUntil: "networkidle" });
const categories = d.getByRole("button", { name: "Categories" });
check("categories starts closed", (await categories.getAttribute("aria-expanded")) === "false");
await categories.focus();
await d.keyboard.press("Enter");
check("Enter opens the menu", (await categories.getAttribute("aria-expanded")) === "true");
check("menu shows real subcategories", await d.getByRole("link", { name: "Claw Clips" }).first().isVisible());
await d.waitForTimeout(150);
await d.screenshot({ path: new URL("mega-menu-desktop.png", out).pathname });
await d.keyboard.press("Tab");
check("Tab moves into the open menu", await d.evaluate(() => document.activeElement?.closest("#nav-panel-categories") !== null), await d.evaluate(() => document.activeElement?.textContent));
await d.keyboard.press("Escape");
check("Escape closes the menu", (await categories.getAttribute("aria-expanded")) === "false");
check("focus returns to the trigger", await d.evaluate(() => document.activeElement?.textContent?.includes("Categories")));
await categories.hover();
check("hover opens on desktop", (await categories.getAttribute("aria-expanded")) === "true");
await d.mouse.move(700, 800);
await d.waitForTimeout(100);
check("moving away closes it", (await categories.getAttribute("aria-expanded")) === "false");
const body = await d.locator("body > header").textContent();
check("hidden: Festive Edit, Gift Box, Anklets", !/Festive Edit|Gift Box|Anklets/.test(body), "no products");
check("shown: New Arrivals, Trending", /New Arrivals/.test(body) && /Trending/.test(body));

const m = await (await browser.newContext({ viewport: { width: 360, height: 740 }, hasTouch: true })).newPage();
await m.goto(`${base}/design`, { waitUntil: "networkidle" });
await m.getByRole("button", { name: "Open menu" }).click();
await m.waitForTimeout(150);
check("mobile menu opens", await m.getByRole("dialog", { name: "Menu" }).isVisible());
await m.getByRole("dialog", { name: "Menu" }).getByText("Jewellery", { exact: true }).click();
await m.waitForTimeout(150);
check("mobile group expands", await m.getByRole("dialog", { name: "Menu" }).getByRole("link", { name: "All Jewellery" }).isVisible());
await m.screenshot({ path: new URL("menu-open-mobile.png", out).pathname });
const small = await m.evaluate(() => [...document.querySelectorAll("dialog a, dialog summary, dialog button")].filter((e) => e.offsetParent && e.getBoundingClientRect().height < 44).length);
check("mobile tap targets are at least 44px high", small === 0, `${small} too small`);
await m.keyboard.press("Escape");
await m.waitForTimeout(100);
check("Escape closes the mobile menu", !(await m.getByRole("dialog", { name: "Menu" }).isVisible()));
await browser.close();
process.exit(failed ? 1 : 0);
