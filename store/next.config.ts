import type { NextConfig } from "next";
import { noStoreHeaderRules } from "./src/lib/cache-policy";

const isDev = process.env.NODE_ENV === "development";

// script-src needs 'unsafe-inline' because Next.js writes inline scripts into pre-rendered pages, and nonces would
// stop those pages being cached. 'unsafe-eval' is added only for `next dev`, which React's development build needs.
const contentSecurityPolicy = [
  "default-src 'self'",
  `script-src 'self' 'unsafe-inline'${isDev ? " 'unsafe-eval'" : ""}`,
  "style-src 'self' 'unsafe-inline'",
  // Google profile pictures, shown on the account page for customers who sign in with Google.
  "img-src 'self' data: https://*.googleusercontent.com",
  "font-src 'self'",
  "connect-src 'self'",
  "frame-ancestors 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "object-src 'none'",
].join("; ");

// For pages and other responses generated by the Worker. Static files get theirs from public/_headers; keep the shared
// values in step. geolocation=(self) lets checkout's "Use my current location" ask for location on NÉVORA's own pages
// only; deploy-test uses geolocation=(), which would turn the button off.
// HSTS starts at one day without includeSubDomains, and is raised only after the custom domain is verified.
// X-Robots-Tag keeps the prototype out of search engines, and is removed deliberately at public launch.
const securityHeaders = [
  { key: "Content-Security-Policy", value: contentSecurityPolicy },
  { key: "Strict-Transport-Security", value: "max-age=86400" },
  { key: "X-Frame-Options", value: "DENY" },
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=(self)" },
  { key: "X-Robots-Tag", value: "noindex, nofollow" },
];

// The template's cacheComponents and partialPrefetching defaults are removed on purpose:
// the store sticks to portable Next.js features.
const nextConfig: NextConfig = {
  poweredByHeader: false,
  async headers() {
    return [
      { source: "/:path*", headers: securityHeaders },
      // The bag, checkout and the planned account, order, admin and API routes are never cached (src/lib/cache-policy.ts).
      // Verified to override Next.js's default one-year s-maxage under both `next start` and OpenNext.
      ...noStoreHeaderRules(),
      // Versioned by PIN_DATA_VERSION in src/lib/pincode.ts. On Cloudflare these files are static assets, so the same
      // rule lives in public/_headers; this one covers `next dev` and `next start`.
      { source: "/data/pin/:path*", headers: [{ key: "Cache-Control", value: "public, max-age=31536000, immutable" }] },
    ];
  },
  turbopack: {
    rules: {
      "*.css": {
        loaders: ["@tailwindcss/turbopack"],
        as: "*.css",
      },
    },
  },
};

export default nextConfig;
